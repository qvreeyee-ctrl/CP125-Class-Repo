def calculate_ractangle_area(length, width):
    area = length * width
    return area

area1 = calculate_ractangle_area(5, 3) 
print(f"Ractangle 1 : {area1:.2f}")

area2 = calculate_ractangle_area(10, 4)
print(f"Ractangle 2: {area2:.2f}")

area3 = calculate_ractangle_area(7, 2)
print(f"Ractangle 3: {area3:.2f}")